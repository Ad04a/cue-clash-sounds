"""Pack the UI and game sounds into three atlases (one Roblox upload each) and write
the Luau region table that roblox/GameSounds.luau reads.

  ui      : ui-sounds (buttons, navigation, loadout_rack)  stereo
  machine : ui-sounds/machine                              mono (works as 3D sounds too)
  game    : ambient-sounds one-shots                       stereo
  loops   : not packed; upload each loop file on its own (Looped sounds can't use a region)

usage: python make_game_atlas.py <output_dir>
writes <output_dir>/roblox/{ui,machine,game}_atlas.ogg and roblox/GameSoundAtlas.luau
"""

import json
import os
import sys

import numpy as np
import soundfile as sf

SR = 48000
GAP = 0.3
PRE = 0.005


def load_manifest(out, folder):
    return json.load(open(os.path.join(out, folder, "manifest.json"), encoding="utf-8"))


def main(out):
    rdir = os.path.join(out, "roblox")
    os.makedirs(rdir, exist_ok=True)
    ui = load_manifest(out, "ui-sounds")
    game = load_manifest(out, "ambient-sounds")
    plan = {
        "ui": (2, "ui-sounds", [e for e in ui if e["group"] != "machine" and not e["loop"]]),
        "machine": (1, "ui-sounds", [e for e in ui if e["group"] == "machine" and not e["loop"]]),
        "game": (2, "ambient-sounds", [e for e in game if not e["loop"]]),
    }
    loops = [("ui-sounds", e) for e in ui if e["loop"]] + [("ambient-sounds", e) for e in game if e["loop"]]

    lua = [
        "--!strict",
        "-- GENERATED by ball-hit-sounds/output/tools/make_game_atlas.py - do not edit by hand.",
        "-- Where every UI / machine / game sound sits inside its atlas (seconds), plus the loop files.",
        "",
        "export type Region = { start: number, length: number }",
        "export type Entry = { atlas: string, regions: { Region } }",
        "",
        "local sounds: { [string]: Entry } = {",
    ]
    for atlas, (ch, folder, entries) in plan.items():
        parts = [np.zeros((int(GAP * SR), ch))]
        pos = len(parts[0])
        for e in entries:
            lua.append(f"\t{e['name']} = {{")
            lua.append(f'\t\tatlas = "{atlas}",')
            lua.append("\t\tregions = {")
            for f in e["files"]:
                x, sr = sf.read(os.path.join(out, folder, f["file"] + ".wav"), always_2d=True)
                assert sr == SR
                if x.shape[1] != ch:
                    x = np.repeat(x, ch, axis=1) if ch == 2 else x.mean(axis=1, keepdims=True)
                lua.append(f"\t\t\t{{ start = {pos / SR - PRE:.4f}, length = {len(x) / SR + PRE:.4f} }},")
                parts += [x, np.zeros((int(GAP * SR), ch))]
                pos += len(x) + int(GAP * SR)
            lua.append("\t\t},")
            lua.append("\t},")
        y = np.concatenate(parts).astype(np.float32)
        path = os.path.join(rdir, f"{atlas}_atlas.ogg")
        with sf.SoundFile(path, "w", SR, ch, format="OGG", subtype="VORBIS") as fh:
            for i in range(0, len(y), 8192):
                fh.write(y[i : i + 8192])
        print(f"{atlas:8s} {len(entries):3d} sounds  {sum(len(e['files']) for e in entries):3d} clips  "
              f"{len(y) / SR:6.1f} s  {ch} ch  {os.path.getsize(path) // 1024} KB")
    lua.append("}")
    lua.append("")
    lua.append("-- Looping sounds: upload each file and give its id to GameSounds.init.")
    lua.append("local loops: { [string]: string } = {")
    for folder, e in loops:
        lua.append(f'\t{e["name"]} = "{folder}/{e["files"][0]["file"]}.ogg",')
    lua.append("}")
    lua.append("")
    lua.append("return { sounds = sounds, loops = loops }")
    with open(os.path.join(rdir, "GameSoundAtlas.luau"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lua) + "\n")
    print("loops:", ", ".join(e["name"] for _, e in loops))


if __name__ == "__main__":
    main(sys.argv[1])
