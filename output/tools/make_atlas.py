"""Pack a bank into ONE audio file + a Luau region table.

Roblox counts every audio upload against a monthly quota, so instead of ~60 uploads
the game uploads one atlas and plays slices of it with Sound.PlaybackRegion.

usage: python make_atlas.py <output_dir>
writes <output_dir>/roblox/impact_atlas_<bank>.ogg|wav and roblox/ImpactAtlas.luau
"""

import glob
import os
import sys

import numpy as np
import soundfile as sf

SR = 48000
GAP = 0.3  # silence between clips
PRE = 0.005  # region starts this much before the clip (codec safety)
BANKS = {
    # folder -> which generated bank it comes from
    "hybrid": {"cue": "recorded", "ball": "recorded", "rail": "synth", "table": "synth", "cluster": "recorded"},
    "synth": {"cue": "synth", "ball": "synth", "rail": "synth", "table": "synth", "cluster": "synth"},
}
LAYERS = ("soft", "medium", "hard")


def main(out):
    rdir = os.path.join(out, "roblox")
    os.makedirs(rdir, exist_ok=True)
    lua = [
        "--!strict",
        "-- GENERATED by ball-hit-sounds/output/tools/make_atlas.py - do not edit by hand.",
        "-- Regions (seconds) of each clip inside impact_atlas_<bank>.ogg.",
        "-- Usage: ImpactAudio.bankFromAtlas(require(ImpactAtlas).hybrid, \"rbxassetid://<atlas id>\")",
        "",
        "export type Region = { start: number, length: number }",
        "",
        "return {",
    ]
    for bank, src in BANKS.items():
        audio = [np.zeros(int(GAP * SR))]
        pos = len(audio[0])
        lua.append(f"\t{bank} = {{")
        for folder, b in src.items():
            lua.append(f"\t\t{folder} = {{")
            for layer in LAYERS:
                regs = []
                for f in sorted(glob.glob(os.path.join(out, "sounds", b, folder, f"{layer}_*.wav"))):
                    x, sr = sf.read(f)
                    assert sr == SR
                    regs.append((pos / SR - PRE, len(x) / SR + PRE))
                    audio += [x, np.zeros(int(GAP * SR))]
                    pos += len(x) + int(GAP * SR)
                lua.append(f"\t\t\t{layer} = {{")
                lua += [f"\t\t\t\t{{ start = {s:.4f}, length = {n:.4f} }}," for s, n in regs]
                lua.append("\t\t\t},")
            lua.append("\t\t},")
        lua.append("\t},")
        y = np.concatenate(audio).astype(np.float32)
        sf.write(os.path.join(rdir, f"impact_atlas_{bank}.wav"), y, SR, subtype="PCM_16")
        # libsndfile's Vorbis encoder crashes on very large single writes: stream it in blocks
        with sf.SoundFile(os.path.join(rdir, f"impact_atlas_{bank}.ogg"), "w", SR, 1, format="OGG", subtype="VORBIS") as fh:
            for i in range(0, len(y), 8192):
                fh.write(y[i : i + 8192])
        print(bank, f"{len(y) / SR:.1f}s", os.path.getsize(os.path.join(rdir, f"impact_atlas_{bank}.ogg")) // 1024, "KB ogg")
    lua.append("}")
    with open(os.path.join(rdir, "ImpactAtlas.luau"), "w", newline="\n") as fh:
        fh.write("\n".join(lua) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
